import React, { useCallback, useEffect, useRef, useState } from 'react';
import { useNavigate, useParams } from 'react-router-dom';
import { useQueryClient } from '@tanstack/react-query';
import { format } from 'date-fns';
import { ptBR } from 'date-fns/locale';
import { ArrowLeft, Captions, RefreshCw, Save, Sparkles, Trash2 } from 'lucide-react';
import { Button, Card, ConfirmDialog, EmptyState, Input, PageHeader, Textarea } from '../components/ui';
import { TranscriptView } from '../components/teleconsult/TranscriptView';
import {
  EMPTY_FORM, formToSummary, HABIT_LABELS, LIST_SECTIONS, summaryToForm, type SummaryForm,
} from '../components/teleconsult/summaryModel';
import { useToast } from '../contexts/ToastContext';
import { supabase } from '../lib/supabase';
import { qk } from '../lib/queryKeys';
import {
  discardTranscript, finishTranscript, generateSummary, getTranscriptByAppointment, getTranscriptSegments,
  saveTranscript, type TeleconsultTranscript, type TranscriptSegment,
} from '../lib/teleconsult';

/**
 * Revisão da transcrição de uma teleconsulta (migration 0044). Ao fim da
 * chamada o nutricionista cai aqui: lê a transcrição, confere o resumo gerado
 * pela IA, corrige o que precisar e escolhe "Salvar no histórico" ou
 * "Descartar". Também serve para editar o resumo de uma já salva.
 */
export const TeleconsultReview: React.FC = () => {
  const { appointmentId = '' } = useParams();
  const navigate = useNavigate();
  const queryClient = useQueryClient();
  const { showToast } = useToast();

  const [transcript, setTranscript] = useState<TeleconsultTranscript | null>(null);
  const [segments, setSegments] = useState<TranscriptSegment[]>([]);
  const [patientName, setPatientName] = useState('');
  const [dateTime, setDateTime] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [form, setForm] = useState<SummaryForm>(EMPTY_FORM);
  const [generating, setGenerating] = useState(false);
  const [summaryError, setSummaryError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);
  const [confirmDiscard, setConfirmDiscard] = useState(false);
  const [discarding, setDiscarding] = useState(false);
  const autoGenerated = useRef(false);

  const runSummary = useCallback(async (id: string) => {
    setGenerating(true);
    setSummaryError(null);
    try {
      setForm(summaryToForm(await generateSummary(id)));
    } catch (err) {
      setSummaryError(err instanceof Error ? err.message : 'Não foi possível gerar o resumo.');
    } finally {
      setGenerating(false);
    }
  }, []);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const { data: appt } = await supabase
          .from('appointments')
          .select('date_time, patients ( name )')
          .eq('id', appointmentId)
          .maybeSingle();
        let t = await getTranscriptByAppointment(appointmentId);
        // Navegador fechou no meio: fecha o rascunho antes de revisar.
        if (t && t.status === 'em_andamento') {
          const hasContent = await finishTranscript(t.id);
          t = hasContent ? await getTranscriptByAppointment(appointmentId) : null;
        }
        const segs = t ? await getTranscriptSegments(t.id) : [];
        if (cancelled) return;
        const patient = (appt?.patients ?? null) as { name?: string } | { name?: string }[] | null;
        setPatientName((Array.isArray(patient) ? patient[0]?.name : patient?.name) ?? '');
        setDateTime(appt?.date_time ?? null);
        setTranscript(t);
        setSegments(segs);
        setForm(summaryToForm(t?.summary));
      } catch (err) {
        if (!cancelled) setLoadError((err as { message?: string })?.message || 'Não foi possível abrir a transcrição.');
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => { cancelled = true; };
  }, [appointmentId]);

  // Primeira abertura do rascunho: gera o resumo sozinho.
  useEffect(() => {
    if (!transcript || transcript.summary || segments.length === 0 || autoGenerated.current) return;
    autoGenerated.current = true;
    const id = window.setTimeout(() => void runSummary(transcript.id), 0);
    return () => window.clearTimeout(id);
  }, [transcript, segments.length, runSummary]);

  const historyPath = transcript ? `/acompanhamento?paciente=${transcript.patient_id}&aba=teleconsultas` : '/agenda';
  const isSaved = transcript?.status === 'salva';
  const set = (key: keyof SummaryForm) => (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement>) =>
    setForm((f) => ({ ...f, [key]: e.target.value }));

  const handleSave = async () => {
    if (!transcript) return;
    setSaving(true);
    try {
      await saveTranscript(transcript.id, formToSummary(form));
      await queryClient.invalidateQueries({ queryKey: qk.teleconsults.byPatient(transcript.patient_id) });
      showToast(isSaved ? 'Resumo atualizado.' : 'Teleconsulta salva no histórico do paciente.', 'success');
      navigate(historyPath, { replace: true });
    } catch (err) {
      showToast((err as { message?: string })?.message || 'Não foi possível salvar.', 'error');
    } finally {
      setSaving(false);
    }
  };

  const handleDiscard = async () => {
    if (!transcript) return;
    setDiscarding(true);
    try {
      await discardTranscript(transcript.id);
      await queryClient.invalidateQueries({ queryKey: qk.teleconsults.byPatient(transcript.patient_id) });
      showToast(isSaved ? 'Transcrição excluída.' : 'Transcrição descartada. Nada foi salvo.', 'success');
      navigate(isSaved ? historyPath : `/agenda?agendamento=${appointmentId}`, { replace: true });
    } catch (err) {
      showToast((err as { message?: string })?.message || 'Não foi possível descartar.', 'error');
    } finally {
      setDiscarding(false);
      setConfirmDiscard(false);
    }
  };

  if (loading) return <p className="text-sm text-slate-500">Carregando a transcrição…</p>;

  if (loadError || !transcript) {
    return (
      <div className="space-y-8">
        <PageHeader title="Revisar teleconsulta" />
        <EmptyState
          icon={<Captions className="h-6 w-6" />}
          title={loadError ? 'Não foi possível abrir' : 'Nada para revisar'}
          description={loadError ?? 'Esta consulta não tem transcrição. Ela só existe quando o paciente aceita o termo e você inicia a transcrição na chamada.'}
          action={<Button variant="secondary" onClick={() => navigate(`/agenda?agendamento=${appointmentId}`)}>Voltar para a agenda</Button>}
        />
      </div>
    );
  }

  return (
    <div className="space-y-8">
      <PageHeader
        title={isSaved ? 'Resumo da teleconsulta' : 'Revisar teleconsulta'}
        description={[
          patientName,
          dateTime ? format(new Date(dateTime), "d 'de' MMMM 'às' HH:mm", { locale: ptBR }) : null,
        ].filter(Boolean).join(' · ')}
        icon={<Captions className="h-5 w-5" />}
        actions={
          <Button variant="ghost" leftIcon={<ArrowLeft className="h-4 w-4" />} onClick={() => navigate(isSaved ? historyPath : `/agenda?agendamento=${appointmentId}`)}>
            Voltar
          </Button>
        }
      />

      {!isSaved && (
        <p role="status" className="rounded-2xl border border-amber-100 bg-amber-50 px-4 py-3 text-sm leading-relaxed text-amber-800">
          Rascunho visível só para você. Confira o resumo gerado pela IA, corrija o que precisar e salve no histórico
          do paciente. Se descartar, a transcrição é apagada de vez.
        </p>
      )}

      <div className="grid gap-6 lg:grid-cols-[minmax(0,1.15fr)_minmax(0,1fr)]">
        <Card as="section" aria-labelledby="summary-title" className="space-y-5">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <h2 id="summary-title" className="flex items-center gap-2 text-base font-semibold text-slate-900">
              <Sparkles className="h-4 w-4 text-[#5024fc]" aria-hidden="true" /> Resumo clínico
            </h2>
            <Button
              variant="secondary"
              size="sm"
              leftIcon={<RefreshCw className="h-4 w-4" />}
              loading={generating}
              disabled={segments.length === 0}
              onClick={() => void runSummary(transcript.id)}
            >
              {transcript.summary || form.resumo_geral ? 'Gerar de novo' : 'Gerar resumo'}
            </Button>
          </div>

          {generating && <p className="text-sm text-slate-500">A IA está lendo a transcrição…</p>}
          {summaryError && (
            <p role="alert" className="rounded-xl border border-rose-100 bg-rose-50 px-3 py-2 text-sm text-rose-700">
              {summaryError} Você pode preencher o resumo à mão ou tentar de novo.
            </p>
          )}

          <fieldset disabled={generating} className="space-y-4">
            <Textarea label="Resumo geral" rows={3} value={form.resumo_geral} onChange={set('resumo_geral')} />
            {LIST_SECTIONS.slice(0, 2).map((s) => (
              <Textarea key={s.key} label={s.label} hint="Um item por linha." rows={3} value={form[s.key]} onChange={set(s.key)} />
            ))}
            <div className="space-y-3 rounded-2xl border border-slate-200 bg-slate-50 p-4">
              <p className="text-sm font-semibold text-slate-700">Hábitos</p>
              {HABIT_LABELS.map((h) => (
                <Input key={h.key} label={h.label} value={form[h.key]} onChange={set(h.key)} />
              ))}
            </div>
            <Textarea label="Condutas" hint="Um item por linha." rows={3} value={form.condutas} onChange={set('condutas')} />
            <Textarea label="Metas" hint="Uma por linha. Prazo depois de um travessão: Reduzir refrigerante — 30 dias" rows={3} value={form.metas} onChange={set('metas')} />
            {LIST_SECTIONS.slice(3).map((s) => (
              <Textarea key={s.key} label={s.label} hint="Um item por linha." rows={2} value={form[s.key]} onChange={set(s.key)} />
            ))}
          </fieldset>
        </Card>

        <Card as="section" aria-labelledby="transcript-title" className="flex max-h-[80vh] flex-col">
          <h2 id="transcript-title" className="text-base font-semibold text-slate-900">Transcrição</h2>
          <p className="mt-1 text-xs text-slate-500">
            Texto automático: pode ter erros de reconhecimento de voz. {segments.length} {segments.length === 1 ? 'trecho' : 'trechos'}.
          </p>
          <div className="mt-4 min-h-0 flex-1 overflow-y-auto rounded-2xl bg-white p-4">
            <TranscriptView segments={segments} />
          </div>
        </Card>
      </div>

      <div className="flex flex-col-reverse gap-2 border-t border-slate-300/50 pt-6 sm:flex-row sm:justify-between">
        <Button variant="ghost" className="text-rose-700 hover:bg-rose-50" leftIcon={<Trash2 className="h-4 w-4" />} onClick={() => setConfirmDiscard(true)}>
          {isSaved ? 'Excluir transcrição' : 'Descartar'}
        </Button>
        <Button leftIcon={<Save className="h-4 w-4" />} loading={saving} disabled={generating} onClick={handleSave}>
          {isSaved ? 'Salvar alterações' : 'Salvar no histórico'}
        </Button>
      </div>

      <ConfirmDialog
        open={confirmDiscard}
        onCancel={() => setConfirmDiscard(false)}
        onConfirm={handleDiscard}
        confirming={discarding}
        title={isSaved ? 'Excluir esta transcrição?' : 'Descartar a transcrição?'}
        message="A transcrição e o resumo são apagados de vez e não podem ser recuperados."
        confirmLabel={isSaved ? 'Excluir' : 'Descartar'}
      />
    </div>
  );
};

export default TeleconsultReview;
